def match_indian_state(code=None, name=None):
    """Map a geolocation region code or name onto a billing state. Empty if unknown."""
    raw_code = (code or '').upper().replace('IN-', '').strip()
    if raw_code in INDIAN_STATE_CODES:
        return INDIAN_STATE_CODES[raw_code]
    cleaned = re.sub(r'\s+', ' ', (name or '').strip())
    if cleaned in INDIAN_STATE_NAMES:
        return cleaned
    return INDIAN_STATE_ALIASES.get(cleaned.lower(), '')


def normalize_gstin(value):
    return re.sub(r'\s+', '', (value or '')).upper()
