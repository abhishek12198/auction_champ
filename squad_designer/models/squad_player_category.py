from odoo import fields, models


class SquadPlayerCategory(models.Model):
    _name = 'squad.player.category'
    _description = 'Player Category'
    _order = 'sequence, name'

    name = fields.Char('Category', required=True, translate=True)
    code = fields.Char('Short Code', size=6, help='e.g. FOR, DOM, CAP, UNC')
    color = fields.Char('Badge Color', default='#1a73e8',
                        help='Hex color for the badge (e.g. #e53935)')
    sequence = fields.Integer(default=10)
    active = fields.Boolean(default=True)
